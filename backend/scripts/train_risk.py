"""Train + evaluate the advisory risk model on SYNTHETIC data and write docs/EVAL_RESULTS.md.
Usage: python scripts/train_risk.py   (run from backend/)"""
import os, sys, platform, datetime
sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))
import joblib, numpy as np, sklearn
from sklearn.ensemble import GradientBoostingClassifier
from sklearn.metrics import (average_precision_score, brier_score_loss, f1_score, precision_score,
                             recall_score, roc_auc_score)
from app.risk import FEATURES, generate_synthetic, heuristic_score

THRESH = 0.5


def metrics(y, score, thr):
    pred = (score >= thr).astype(int)
    return {"precision": precision_score(y, pred, zero_division=0), "recall": recall_score(y, pred),
            "f1": f1_score(y, pred), "roc_auc": roc_auc_score(y, score),
            "pr_auc": average_precision_score(y, score), "fpr": float(((pred == 1) & (y == 0)).sum() / max((y == 0).sum(), 1)),
            "brier": brier_score_loss(y, np.clip(score, 0, 1))}


def main():
    Xtr, ytr = generate_synthetic(20000, seed=1)
    sets = {"in-distribution test (seed 2)": generate_synthetic(8000, seed=2),
            "shifted test (seed 3, benign drift +0.4)": generate_synthetic(8000, seed=3, shift=0.4)}
    model = GradientBoostingClassifier(n_estimators=120, max_depth=3, random_state=0).fit(Xtr, ytr)
    os.makedirs("models", exist_ok=True)
    joblib.dump(model, "models/risk_model.joblib")

    def rule(X):  # baseline 1: "flag if purchase is >= 60% of per-purchase limit"
        return (X[:, FEATURES.index("amount_ratio")] >= 0.6).astype(float)

    def heur(X):  # baseline 2: transparent hand-weighted heuristic
        return np.array([heuristic_score(dict(zip(FEATURES, r))) for r in X])

    lines = ["# Risk model evaluation (SYNTHETIC DATA ONLY)", "",
             "> Generated by `backend/scripts/train_risk.py`. Data is **synthetic** (see `risk.generate_synthetic`); "
             "these numbers do **not** describe real-world fraud or agent-misbehaviour rates.", "",
             f"Run: {datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds')} | python {platform.python_version()} | "
             f"scikit-learn {sklearn.__version__} | train n=20000 (anomaly rate 12%), threshold {THRESH}", ""]
    for name, (X, y) in sets.items():
        lines += [f"## {name}", "", f"n={len(y)}, positives={int(y.sum())}", "",
                  "| Method | Precision | Recall | F1 | FPR | ROC-AUC | PR-AUC | Brier |", "|---|---|---|---|---|---|---|---|"]
        for label, score in (("Baseline: amount-ratio rule", rule(X)), ("Baseline: hand-weighted heuristic", heur(X)),
                             ("Gradient boosting", model.predict_proba(X)[:, 1])):
            m = metrics(y, score, THRESH)
            lines.append(f"| {label} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} | {m['fpr']:.3f} | "
                         f"{m['roc_auc']:.3f} | {m['pr_auc']:.3f} | {m['brier']:.3f} |")
        lines.append("")
    imp = sorted(zip(FEATURES, model.feature_importances_), key=lambda t: -t[1])
    lines += ["## Feature importances (gradient boosting)", ""] + [f"- {k}: {v:.3f}" for k, v in imp]
    lines += ["", "## Interpretation limits", "",
              "- Labels come from the same generator that defines the features, so absolute scores are optimistic.",
              "- The score is advisory: it can only escalate a purchase to human review; deterministic mandate rules decide DENY.",
              "- Rule baseline AUC is computed from a binary score, so its ROC/PR-AUC are not comparable to continuous scores."]
    open("../docs/EVAL_RESULTS.md", "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
